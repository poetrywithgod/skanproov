import { runCode } from "@skanproov/validation";
import Link from "next/link";
import type { CodeRun } from "@/lib/manufacturer/code-run-shared";
import { site } from "@/lib/site";
import { formatNumber } from "../products/bits";

function when(iso: string): string {
  const date = new Date(iso);
  const day = date.toLocaleDateString("en-GB", { day: "numeric", month: "short", year: "numeric", timeZone: "Africa/Lagos" });
  const time = date.toLocaleTimeString("en-US", { hour: "2-digit", minute: "2-digit", timeZone: "Africa/Lagos" });
  return `${day} · ${time}`;
}

function DownloadLink({ run, kind, label }: { run: CodeRun; kind: "csv" | "pdf"; label: string }) {
  return (
    <a
      href={`${site.manufacturer.codes}/download/${run.id}/${kind}`}
      className="inline-flex items-center gap-1.5 text-sm font-semibold text-retail hover:underline"
    >
      <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.8" strokeLinecap="round" strokeLinejoin="round" className="size-4" aria-hidden="true">
        <path d="M12 4v11m0 0-4-4m4 4 4-4M5 20h14" />
      </svg>
      {label}
    </a>
  );
}

/** Recent generations: what was made, by whom, and the files while they are still kept. */
export function RunsTable({ runs }: { runs: CodeRun[] }) {
  return (
    <div className="overflow-x-auto">
      <table className="w-full min-w-[820px] text-left text-[15px]">
        <thead>
          <tr className="bg-[#f7f8f7] text-xs font-semibold text-body">
            <th scope="col" className="px-6 py-3.5">Generation ID</th>
            <th scope="col" className="px-3 py-3.5">Product / Batch</th>
            <th scope="col" className="px-3 py-3.5">Codes</th>
            <th scope="col" className="px-3 py-3.5">Generated on</th>
            <th scope="col" className="px-3 py-3.5">Generated by</th>
            <th scope="col" className="px-3 py-3.5">Status</th>
            <th scope="col" className="px-6 py-3.5 text-right">Action</th>
          </tr>
        </thead>
        <tbody className="divide-y divide-row-line">
          {runs.map((run) => {
            const ready = Boolean(run.csvPath && run.pdfPath);
            return (
              <tr key={run.id}>
                <td className="whitespace-nowrap px-6 py-4 font-medium text-ink">{runCode(run.runNo)}</td>
                <td className="px-3 py-4">
                  <p className="font-semibold text-ink">{[run.productName, run.variant].filter(Boolean).join(" · ")}</p>
                  <Link href={`${site.manufacturer.batches}/${run.batchId}`} className="text-xs text-muted hover:underline">
                    {run.batchNumber}
                  </Link>
                </td>
                <td className="px-3 py-4 text-body">{formatNumber(run.quantity)}</td>
                <td className="whitespace-nowrap px-3 py-4 text-body">{when(run.createdAt)}</td>
                <td className="px-3 py-4 text-muted">{run.generatedByName ?? "—"}</td>
                <td className="px-3 py-4">
                  <span className={`inline-flex rounded-full px-3 py-1 text-[13px] font-medium ${ready ? "bg-retail-soft text-retail-dark" : "bg-pill text-muted"}`}>
                    {ready ? "Ready" : "Expired"}
                  </span>
                </td>
                <td className="px-6 py-4">
                  {ready ? (
                    <div className="flex items-center justify-end gap-4">
                      <DownloadLink run={run} kind="csv" label="CSV" />
                      <DownloadLink run={run} kind="pdf" label="Labels" />
                    </div>
                  ) : (
                    <p className="text-right text-xs text-muted">Files deleted after 30 days</p>
                  )}
                </td>
              </tr>
            );
          })}
        </tbody>
      </table>
    </div>
  );
}
